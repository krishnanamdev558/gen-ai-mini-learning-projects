import streamlit as st
import os
from langchain_groq import ChatGroq
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_classic.chains.combine_documents import create_stuff_documents_chain
from langchain_core.prompts import ChatPromptTemplate
from langchain_classic.chains import create_retrieval_chain
from langchain_community.vectorstores import FAISS
from langchain_community.document_loaders import PyPDFDirectoryLoader
from langchain_huggingface import HuggingFaceEmbeddings
from dotenv import load_dotenv
load_dotenv()

## loading groq api key from environment variable
groq_api_key = os.getenv("GROQ_API_KEY")
os.environ["HF_TOKEN"] = os.getenv("HUGGINGFACE_API_KEY")

## Initialize the ChatGroq model with the specified model name and API key
model = ChatGroq(
    model="openai/gpt-oss-120b",
    api_key=groq_api_key)

## prompt template for the chat model
from langchain_core.prompts import ChatPromptTemplate

prompt_template = ChatPromptTemplate.from_template(
    """
    Answer the questions based on the provided context only.
    Please provide the most accurate respone based on the question
    <context>
    {context}
    <context>
    Question:{input}

    """

)

## embeddings model for vectorization
# chunk->embed->store->retrieve->answer

def create_vectorstore_from_pdfs():
    if "vectors" not in st.session_state:
        st.session_state.embeddings = HuggingFaceEmbeddings(model="sentence-transformers/all-mpnet-base-v2")   ## initialize the embeddings model for vectorization
        st.session_state.loader = PyPDFDirectoryLoader("research_papers")   ## data ingestion from research papers
        st.session_state.documents = st.session_state.loader.load()     ## laod documents from the specified directory to the session state
        st.session_state.text_splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=200)     ## initialize the text splitter with specified chunk size and overlap
        st.session_state.chunks = st.session_state.text_splitter.split_documents(st.session_state.documents)    ## it splits the documents into smaller chunks for better embedding
        st.session_state.vectors = FAISS.from_documents(st.session_state.chunks, st.session_state.embeddings)   ## create embeddings for the chunks using OllamaEmbeddings and store them in FAISS vectorstore  

st.title("RAG Document Q&A With Groq And HuggingFace Embeddings")

user_prompt = st.text_input("Enter your question:", "")


if st.button("Document Embedding"):
    create_vectorstore_from_pdfs()
    st.write("Document embedding completed and stored in FAISS vectorstore.")


import time

if user_prompt:
    document_chain = create_stuff_documents_chain(model, prompt_template)
    retriever = st.session_state.vectors.as_retriever()     
    retrieval_chain = create_retrieval_chain(retriever,document_chain)

    start=time.process_time()
    response=retrieval_chain.invoke({'input':user_prompt})
    print(f"Response time :{time.process_time()-start}")

    st.write(response['answer'])  ## display the response generated by the retrieval chain based on the user prompt and retrieved documents
    



